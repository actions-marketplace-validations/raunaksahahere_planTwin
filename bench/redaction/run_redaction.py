"""Measure the fidelity cost of each redaction mode, on the demo dataset.

Run:      python3 run_redaction.py            (needs ./bin/plantwin from `make build`, and Docker)
Analyse:  python3 run_redaction.py --analyse-only   (uses the saved runs; no containers)

For each mode (keep, hash, drop-mcv, drop-histogram) the script runs `plantwin demo --keep --redaction <mode>` three
times and copies each run's last-run.json (both plan trees per query, and the findings) to
bench/results/redaction/<mode>/runN/.

Analysis compares every run with every keep run (a run is never compared with itself):
  - plan shape agreement, per query and side (base, head);
  - relative error of the top node's total cost (the top row count is 1 for count(*) queries, so it cannot show
    estimate changes; cost can);
  - verdict agreement: the set of (query, rule) findings equals the keep run's set.
keep compared with keep is reported as the noise floor.
"""
import json
import os
import re
import shutil
import statistics
import subprocess
import sys

REPO = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
OUT = os.path.join(REPO, "bench", "results", "redaction")
BIN = os.path.join(REPO, "bin", "plantwin")
MODES = ["keep", "hash", "drop-mcv", "drop-histogram"]
RUNS = 3
TWIN_NAME = re.compile(r"^plantwin-[0-9a-f]{8}-(base|head)$")


def remove_twins():
    """Remove only twin containers that PlanTwin names plantwin-<run-id>-base|head."""
    names = subprocess.run(["docker", "ps", "-a", "--format", "{{.Names}}"], capture_output=True, text=True).stdout.split()
    for n in names:
        if TWIN_NAME.match(n):
            subprocess.run(["docker", "rm", "-f", n], capture_output=True)


def run_demo(mode):
    remove_twins()
    proc = subprocess.run([BIN, "demo", "--keep", "--format", "json", "--redaction", mode], capture_output=True, text=True)
    m = re.search(r"^Demo repository: (.+)$", proc.stderr, re.M)
    if not m:
        sys.exit(f"demo did not print its directory: {proc.stderr[-400:]}")
    remove_twins()
    return m.group(1).strip()


def shape(node, acc):
    acc.append((node["Node Type"], node.get("Relation Name"), node.get("Index Name")))
    for c in node.get("Plans", []):
        shape(c, acc)
    return acc


def load(mode, run):
    data = json.load(open(os.path.join(OUT, mode, f"run{run}", "last-run.json")))
    plans = {p["name"]: {"base": p.get("base"), "head": p.get("head")} for p in data["plans"]}
    findings = set()
    for q in data["run"].get("Queries") or []:
        for f in q.get("findings") or []:
            findings.add((q["name"], f["rule"]))
    return plans, findings


def rel_err(a, b):
    return abs(a - b) / max(abs(a), 1e-9)


def compare(mode, run, refs):
    """Compare one run with each reference run. Returns counts and error lists."""
    pm, fm = load(mode, run)
    out = {"shape_ok": 0, "shape_total": 0, "cost_err": [], "verdict_ok": 0, "verdict_total": 0, "changed": set()}
    for rmode, rrun in refs:
        pr, fr = load(rmode, rrun)
        for q in pr:
            for side in ("base", "head"):
                a, b = pr[q][side], pm.get(q, {}).get(side)
                if a is None or b is None:
                    continue
                out["shape_total"] += 1
                if shape(a, []) == shape(b, []):
                    out["shape_ok"] += 1
                else:
                    out["changed"].add(f"{q}/{side}")
                out["cost_err"].append(rel_err(a["Total Cost"], b["Total Cost"]))
        out["verdict_total"] += 1
        if fm == fr:
            out["verdict_ok"] += 1
    return out


def main():
    analyse_only = "--analyse-only" in sys.argv
    if not analyse_only:
        if not os.path.exists(BIN):
            sys.exit("bin/plantwin is missing: run `make build` first")
        if os.path.exists(OUT):
            shutil.rmtree(OUT)
        os.makedirs(OUT)
        demo_dirs = []
        for mode in MODES:
            for run in range(1, RUNS + 1):
                d = run_demo(mode)
                demo_dirs.append(d)
                dest = os.path.join(OUT, mode, f"run{run}")
                os.makedirs(dest, exist_ok=True)
                shutil.copy(os.path.join(d, ".plantwin", "last-run.json"), os.path.join(dest, "last-run.json"))
                print(f"{mode} run {run}: done", flush=True)
        for d in demo_dirs:
            if os.path.basename(d).startswith("plantwin-demo-") and os.path.isdir(d):
                shutil.rmtree(d)

    keep_refs = [("keep", r) for r in range(1, RUNS + 1)]
    lines = ["# Redaction fidelity (generated)", "",
             "Generated by `bench/redaction/run_redaction.py` from `bench/results/redaction/`. Do not edit by hand.", "",
             "Dataset: the built-in demo (500k synthetic orders, two queries, a migration that drops `orders_customer_idx`).",
             f"Each mode ran {RUNS} times. Every run is compared with the keep runs (never with itself).", "",
             "| Mode | Shape agreement with keep | Median top-cost error (base and head) | Verdict agreement with keep | Plan-query sides that changed shape |",
             "|---|---:|---:|---:|---|"]
    details = []
    for mode in MODES:
        ok = tot = vok = vtot = 0
        costs, changed = [], set()
        for run in range(1, RUNS + 1):
            refs = [r for r in keep_refs if not (mode == "keep" and r[1] == run)]
            c = compare(mode, run, refs)
            ok += c["shape_ok"]
            tot += c["shape_total"]
            vok += c["verdict_ok"]
            vtot += c["verdict_total"]
            costs += c["cost_err"]
            changed |= c["changed"]
        label = mode + (" (reference)" if mode == "keep" else "")
        med = statistics.median(costs) * 100 if costs else 0.0
        lines.append(f"| {label} | {ok}/{tot} | {med:.2f}% | {vok}/{vtot} | {', '.join(sorted(changed)) or '-'} |")

    # Noise floor: keep against the other keep runs.
    nf_ok = nf_tot = 0
    for run in range(1, RUNS + 1):
        c = compare("keep", run, [r for r in keep_refs if r[1] != run])
        nf_ok += c["shape_ok"]
        nf_tot += c["shape_total"]
    lines += ["", f"Noise floor (keep against keep, runs that did not share an ANALYZE sample): shape agreement {nf_ok}/{nf_tot}.",
              "", "Top-cost error is the relative difference of the top node's total cost. It is used because the top node of a",
              "count(*) query always returns one row, so row estimates cannot show changes there.",
              "Small sample: one synthetic dataset, two queries, one PostgreSQL version, three runs per mode."]
    open(os.path.join(OUT, "fidelity.md"), "w").write("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
