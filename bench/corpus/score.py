"""Score the corpus: compare the tool's verdict per case with the measured ground truth.

usage: score.py <results_dir> <out_md>
Ground truth per query: REGRESSION if the head query fails to plan, or if the median head runtime is at least
RATIO times the median base runtime and the base runtime is at least MIN_MS. A case is a regression if any query is.
Prediction per case: the tool flags it if any finding is a warning or an error.
Layout: <results_dir>/truth/{base,<case>}/, <results_dir>/plans/<case>/{base,head}/, <results_dir>/findings/<case>.json,
<results_dir>/cases/<case>.json (estimated tables and the migration). Writes a Markdown report.
"""
import json, os, sys

RATIO, MIN_MS = 2.0, 20.0
res, out_md = sys.argv[1:3]
cases = sorted(f[:-5] for f in os.listdir(os.path.join(res, "findings")) if f.endswith(".json"))
base_truth = os.path.join(res, "truth", "base")

def truth_for(case, ratio=None):
    """Return (case_is_regression, [reasons]) from the measured runtimes at the given ratio (default RATIO)."""
    ratio = RATIO if ratio is None else ratio
    reasons = []
    d = os.path.join(res, "truth", case)
    for q in sorted(f[:-5] for f in os.listdir(base_truth) if f.endswith(".json") or f.endswith(".err")):
        if q.endswith(".err") or not os.path.exists(os.path.join(base_truth, q + ".json")):
            continue
        b = json.load(open(os.path.join(base_truth, q + ".json")))["median_ms"]
        hp = os.path.join(d, q + ".json")
        if os.path.exists(os.path.join(d, q + ".err")):
            reasons.append(f"{q}: head query fails")
        elif os.path.exists(hp):
            h = json.load(open(hp))["median_ms"]
            # The absolute floor applies to the head time: a query that goes from 0.1 ms to 30 ms is a real regression.
            if h >= MIN_MS and h >= ratio * b:
                reasons.append(f"{q}: {b:.2f} ms -> {h:.1f} ms ({h / b:.0f}x)")
    return bool(reasons), reasons

rows, tp, fn, fp, tn = [], 0, 0, 0, 0
for case in cases:
    meta = json.load(open(os.path.join(res, "cases", case + ".json")))
    findings = json.load(open(os.path.join(res, "findings", case + ".json")))
    flagged = sorted({f["query"] for r in findings for f in r["findings"] if f["severity"] in ("error", "warning")})
    rule_names = sorted({f["rule"] for r in findings for f in r["findings"] if f["severity"] in ("error", "warning")})
    predicted = bool(flagged)
    truth, reasons = truth_for(case)
    if truth and predicted: tp += 1
    elif truth and not predicted: fn += 1
    elif not truth and predicted: fp += 1
    else: tn += 1
    verdict = {(True, True): "TP", (True, False): "FN", (False, True): "FP", (False, False): "TN"}[(truth, predicted)]
    rows.append((case, verdict, "yes" if truth else "no", "yes" if predicted else "no", ", ".join(rule_names) or "-", "; ".join(reasons) or "-"))

pos, neg = tp + fn, fp + tn

# Sensitivity: the verdict depends on the runtime bar. Predictions are fixed; only the ground truth moves.
sens = ["| Runtime bar | Measured regressions | Recall | False positives | False-positive rate |", "|---|---:|---:|---:|---:|"]
for bar in (1.5, 2.0, 3.0):
    t_pos = t_fp = t_neg = t_tp = 0
    for case in cases:
        findings = json.load(open(os.path.join(res, "findings", case + ".json")))
        predicted = any(f["severity"] in ("error", "warning") for r in findings for f in r["findings"])
        truth, _ = truth_for(case, bar)
        t_pos += truth
        t_neg += not truth
        t_tp += truth and predicted
        t_fp += (not truth) and predicted
    rec = f"{t_tp}/{t_pos} = {t_tp / t_pos * 100:.0f}%" if t_pos else "n/a"
    fpr = f"{t_fp}/{t_neg} = {t_fp / t_neg * 100:.0f}%" if t_neg else "n/a"
    sens.append(f"| {bar:.1f}x | {t_pos} | {rec} | {t_fp} | {fpr} |")
recall = tp / pos * 100 if pos else float("nan")
fpr = fp / neg * 100 if neg else float("nan")
lines = ["# Migration corpus: recall and false-positive rate (generated)", "",
         "Generated by `bench/corpus/score.py` from `bench/results/corpus/`. Do not edit by hand.", "",
         f"Cases: {len(cases)} ({pos} measured regressions, {neg} measured non-regressions). "
         f"Ground truth: a query regresses if its head runtime is at least {RATIO}x its base runtime (base at least {MIN_MS:.0f} ms), or the head query fails to plan.", "",
         f"- Recall: **{tp}/{pos} = {recall:.0f}%**" if pos else "- Recall: no measured regressions",
         f"- False-positive rate: **{fp}/{neg} = {fpr:.0f}%**" if neg else "- False-positive rate: no measured non-regressions",
         f"- Confusion: TP {tp}, FN {fn}, FP {fp}, TN {tn}", "",
         "| Case | Verdict | Measured regression | Tool flags | Rules fired | Measured evidence |",
         "|---|---|---|---|---|---|"]
for r in rows:
    lines.append("| " + " | ".join(r) + " |")
lines += ["", "Sensitivity to the runtime bar (predictions fixed, ground truth recomputed from the same measurements):", ""] + sens + ["", "Verdicts: TP = regression, flagged; FN = regression, missed; FP = no regression, flagged; TN = no regression, not flagged.",
          f"Small sample: {len(cases)} cases, one synthetic dataset, one PostgreSQL version. The rules were developed on the first 12 cases (c01-c12), so this is not a held-out evaluation; c13-c18 were added afterwards and no rule was changed for them. These numbers do not generalise without a larger, held-out corpus."]
open(out_md, "w").write("\n".join(lines) + "\n")
print("\n".join(lines[:8]))
